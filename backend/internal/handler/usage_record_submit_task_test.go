// TestGatewayHandlerSubmitUsageRecordTaskForMedia_NonMediaUsesDroppablePath
// 守护不误伤：无媒体产出（nil result 或 ImageCount=VideoCount=0）的文本请求仍走可丢弃的
// 普通路径，任务由 worker 池正常执行，不会被强制同步。
func TestGatewayHandlerSubmitUsageRecordTaskForMedia_NonMediaUsesDroppablePath(t *testing.T) {
	pool := newUsageRecordTestPool(t)
	h := &GatewayHandler{usageRecordWorkerPool: pool}

	done := make(chan struct{})
	// nil result 与纯文本 result 都应走普通路径并被池执行。
	h.submitUsageRecordTaskForMedia(context.Background(), nil, func(ctx context.Context) {
		close(done)
	})
	select {
	case <-done:
	case <-time.After(time.Second):
		t.Fatal("non-media task should be enqueued and executed via droppable path")
	}
}
